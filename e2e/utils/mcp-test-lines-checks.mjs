/**
 * Pure helpers for `verify-mcp-test-lines.mjs` (PILOT-1239): read the test
 * line an MCP action tool answered with, and build the spec that replays a
 * walk's lines. Kept apart from the script so they are unit-tested without a
 * device (`utils/__tests__/mcp-test-lines-checks.test.mjs`).
 */

import { resultText } from "./mcp-first-snapshot-checks.mjs"

/**
 * The test line an action tool's JSON-RPC response carries, or the problem
 * with it. A position-dependent line is still a line (its comment goes into
 * the test with it); an unverified one is a problem: the walk uses locators
 * the device can check.
 *
 * @param {object | undefined} response the JSON-RPC response to `tools/call`
 * @returns {{ line: string, positional: boolean, replaced: boolean } | { problem: string }}
 */
export function testLineOf(response) {
  if (!response) return { problem: "no response from the MCP server" }
  if (response.error) return { problem: `protocol error: ${JSON.stringify(response.error)}` }
  const text = resultText(response)
  if (response.result?.isError) return { problem: `the action failed: ${text.slice(0, 500) || "(no message)"}` }
  const lines = text.split("\n")
  if (lines[0] !== "OK") return { problem: `the result does not start with OK: ${text.slice(0, 300)}` }
  const match = /^Test line( \(position-dependent\))?: (.*)$/.exec(lines[1] ?? "")
  if (!match) return { problem: `no test line in the result: ${text.slice(0, 300)}` }
  if (match[2].startsWith("none")) return { problem: `the line was not verified: ${match[2]}` }
  return {
    line: match[2],
    positional: match[1] !== undefined,
    replaced: lines.slice(2).some((l) => /picks its element by position; the device agent matched this locator/.test(l)),
  }
}

/**
 * A spec that replays `lines` in one test, then checks `finalCheck` (a
 * statement) to show the replay reached the screen the walk did.
 *
 * @param {string[]} lines
 * @param {string} finalCheck
 * @returns {string}
 */
export function replaySpec(lines, finalCheck) {
  const body = [...lines, finalCheck].map((l) => `  ${l}`).join("\n")
  return [
    "// Generated by verify-mcp-test-lines.mjs from the test lines an MCP walk answered with.",
    'import { expect, test } from "tapsmith"',
    "",
    'test("replays the lines of an MCP walk", async ({ device }) => {',
    body,
    "})",
    "",
  ].join("\n")
}
