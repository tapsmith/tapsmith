// Expo config plugin that adds a native Android Views settings screen, opened
// with the deep link tapsmithnative://settings.
//
// Its rows have the accessibility tree of androidx's SwitchPreferenceCompat and
// CheckBoxPreference: a clickable row in a ListView holding the title and
// summary, and in its widget frame a switch or checkbox that is neither
// clickable nor focusable and has no text of its own. TalkBack reads such a row
// as "Full black, off, switch"; Tapsmith names the control by its row the same
// way. Plain framework widgets keep the app free of an androidx.preference
// dependency while giving the agent the same nodes. React Native can't render
// this shape: its Switch is always clickable. Android only.
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins")
const { mkdirSync, writeFileSync } = require("fs")
const { join } = require("path")

const ACTIVITY = "NativeSettingsActivity"
const SCHEME = "tapsmithnative"

const ACTIVITY_SOURCE = (pkg) => `// Generated by test-app/plugins/with-native-settings-screen.js. Do not edit.
package ${pkg}

import android.app.Activity
import android.graphics.Color
import android.os.Bundle
import android.util.TypedValue
import android.view.Gravity
import android.view.View
import android.view.ViewGroup
import android.widget.BaseAdapter
import android.widget.CheckBox
import android.widget.CompoundButton
import android.widget.FrameLayout
import android.widget.LinearLayout
import android.widget.ListView
import android.widget.RelativeLayout
import android.widget.Switch
import android.widget.TextView

class ${ACTIVITY} : Activity() {
  private class Pref(val title: String, val summary: String?, val checkbox: Boolean, var on: Boolean, val ownFocus: Boolean = false)

  private val prefs = listOf(
    Pref("Full black", "Use full black for the dark theme", checkbox = false, on = false),
    Pref("Dynamic colors", "Adapt app colors based on the wallpaper", checkbox = false, on = true),
    Pref("Download on Wi-Fi only", null, checkbox = true, on = false),
    // A switch TalkBack focuses on its own: the row does not name it.
    Pref("Sync now", "Runs once", checkbox = false, on = false, ownFocus = true),
  )

  private lateinit var status: TextView

  private fun dp(value: Int): Int =
    TypedValue.applyDimension(TypedValue.COMPLEX_UNIT_DIP, value.toFloat(), resources.displayMetrics).toInt()

  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val root = LinearLayout(this).apply {
      orientation = LinearLayout.VERTICAL
      fitsSystemWindows = true
      setBackgroundColor(Color.WHITE)
    }
    root.addView(TextView(this).apply {
      text = "Native settings"
      setTextSize(TypedValue.COMPLEX_UNIT_SP, 22f)
      setTextColor(Color.BLACK)
      setPadding(dp(16), dp(16), dp(16), dp(8))
    })
    status = TextView(this).apply {
      setTextColor(Color.DKGRAY)
      setPadding(dp(16), 0, dp(16), dp(8))
    }
    root.addView(status)
    updateStatus()
    root.addView(ListView(this).apply {
      adapter = PrefAdapter()
      itemsCanFocus = true
    }, LinearLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, 0, 1f))
    setContentView(root)
  }

  private fun updateStatus() {
    status.text = prefs.joinToString(" · ") { "\${it.title}: \${if (it.on) "on" else "off"}" }
  }

  private inner class PrefAdapter : BaseAdapter() {
    override fun getCount(): Int = prefs.size
    override fun getItem(position: Int): Any = prefs[position]
    override fun getItemId(position: Int): Long = position.toLong()

    override fun getView(position: Int, convertView: View?, parent: ViewGroup): View {
      val pref = prefs[position]
      val row = LinearLayout(this@${ACTIVITY}).apply {
        orientation = LinearLayout.HORIZONTAL
        gravity = Gravity.CENTER_VERTICAL
        minimumHeight = dp(72)
        setPadding(dp(16), dp(8), dp(16), dp(8))
      }
      // The title and summary, as androidx Preference lays them out.
      val texts = RelativeLayout(this@${ACTIVITY})
      val title = TextView(this@${ACTIVITY}).apply {
        id = View.generateViewId()
        text = pref.title
        setTextSize(TypedValue.COMPLEX_UNIT_SP, 18f)
        setTextColor(Color.BLACK)
      }
      texts.addView(title)
      if (pref.summary != null) {
        texts.addView(TextView(this@${ACTIVITY}).apply {
          text = pref.summary
          setTextColor(Color.DKGRAY)
        }, RelativeLayout.LayoutParams(ViewGroup.LayoutParams.WRAP_CONTENT, ViewGroup.LayoutParams.WRAP_CONTENT).apply {
          addRule(RelativeLayout.BELOW, title.id)
        })
      }
      row.addView(texts, LinearLayout.LayoutParams(0, ViewGroup.LayoutParams.WRAP_CONTENT, 1f))
      // The widget frame and its control: no text of its own.
      val frame = FrameLayout(this@${ACTIVITY})
      val control: CompoundButton = if (pref.checkbox) CheckBox(this@${ACTIVITY}) else Switch(this@${ACTIVITY})
      control.isChecked = pref.on
      if (pref.ownFocus) {
        control.setOnCheckedChangeListener { _, checked ->
          pref.on = checked
          updateStatus()
        }
      } else {
        control.isClickable = false
        control.isFocusable = false
        row.isClickable = true
        row.isFocusable = true
        row.setOnClickListener {
          pref.on = !pref.on
          control.isChecked = pref.on
          updateStatus()
        }
      }
      frame.addView(control)
      row.addView(frame)
      return row
    }
  }
}
`

module.exports = function withNativeSettingsScreen(config) {
  config = withDangerousMod(config, [
    "android",
    (mod) => {
      const pkg = mod.android?.package ?? config.android?.package
      const dir = join(
        mod.modRequest.platformProjectRoot,
        "app/src/main/java",
        ...pkg.split("."),
      )
      mkdirSync(dir, { recursive: true })
      writeFileSync(join(dir, `${ACTIVITY}.kt`), ACTIVITY_SOURCE(pkg))
      return mod
    },
  ])
  return withAndroidManifest(config, (mod) => {
    const app = mod.modResults.manifest.application?.[0]
    if (!app) return mod
    app.activity = (app.activity ?? []).filter((a) => a.$["android:name"] !== `.${ACTIVITY}`)
    app.activity.push({
      $: {
        "android:name": `.${ACTIVITY}`,
        "android:exported": "true",
        "android:label": "Native settings",
      },
      "intent-filter": [
        {
          action: [{ $: { "android:name": "android.intent.action.VIEW" } }],
          category: [
            { $: { "android:name": "android.intent.category.DEFAULT" } },
            { $: { "android:name": "android.intent.category.BROWSABLE" } },
          ],
          data: [{ $: { "android:scheme": SCHEME } }],
        },
      ],
    })
    return mod
  })
}
