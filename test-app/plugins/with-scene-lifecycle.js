// Expo config plugin that moves the iOS app onto the UIScene life cycle.
//
// iOS 27 kills an app built against the iOS 27 SDK at launch
// (_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption) unless it
// adopts scenes, and the Expo SDK 55 template still creates its window in the
// app delegate. Expo SDK 58's template adopts scenes with a SceneDelegate built
// on ExpoAppSceneDelegate, which SDK 55 does not have, so this plugin does the
// same by hand:
//   - Info.plist gets a UIApplicationSceneManifest naming SceneDelegate;
//   - AppDelegate stops creating the window and starting React Native;
//   - SceneDelegate.swift creates the window from the scene, starts React
//     Native with the cold-start URL as launch options, and forwards URL,
//     user-activity and life-cycle events to the app delegate (which passes
//     them on to the Expo subscribers and RCTLinkingManager).
// Builds with Xcode 26 behave the same: the scene life cycle works on every iOS
// version the app supports. Remove this plugin when upgrading to Expo SDK 58+.
const {
  IOSConfig,
  withAppDelegate,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins")
const { writeFileSync } = require("fs")
const { join } = require("path")

const SCENE_DELEGATE_FILE = "SceneDelegate.swift"

// The SDK 55 template's window setup in didFinishLaunchingWithOptions.
const APP_DELEGATE_WINDOW_SETUP =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\)\n#endif\n/
const APP_DELEGATE_MARKER = "// The window is created and React Native started by SceneDelegate"

const SCENE_DELEGATE = `// Generated by test-app/plugins/with-scene-lifecycle.js. Do not edit.
internal import Expo
import React

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }
    guard let appDelegate, let factory = appDelegate.reactNativeFactory else {
      fatalError("SceneDelegate: AppDelegate did not create its React Native factory")
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window keeps working.
    appDelegate.window = window

    // Under scenes, UIKit passes a cold-start URL in connectionOptions, not in
    // the app delegate's launch options, and Linking.getInitialURL() reads only
    // the launch options. Rebuild them, keyed by the raw strings React Native
    // reads (the UIApplication.LaunchOptionsKey accessors are deprecated).
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    if let activity = connectionOptions.userActivities.first(where: {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }) {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey")] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions.isEmpty ? nil : launchOptions)

    // Let the Expo subscribers (expo-linking's initial URL) see them too.
    connectionOptions.urlContexts.forEach { open($0) }
    connectionOptions.userActivities.forEach { continueActivity($0) }
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  // Deep links. UIKit no longer calls application(_:open:options:) under
  // scenes, so hand each one to the app delegate's handler.
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    URLContexts.forEach { open($0) }
  }

  // Universal links.
  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    continueActivity(userActivity)
  }

  private func open(_ context: UIOpenURLContext) {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [
      .openInPlace: context.options.openInPlace,
    ]
    if let sourceApplication = context.options.sourceApplication {
      options[.sourceApplication] = sourceApplication
    }
    if let annotation = context.options.annotation {
      options[.annotation] = annotation
    }
    _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
  }

  private func continueActivity(_ activity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: activity) { _ in }
  }
}
`

function withSceneManifest(config) {
  return withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    }
    return mod
  })
}

function withoutAppDelegateWindow(config) {
  return withAppDelegate(config, (mod) => {
    const { contents, language } = mod.modResults
    if (language !== "swift") {
      throw new Error(`with-scene-lifecycle: expected a Swift AppDelegate, got ${language}`)
    }
    if (contents.includes(APP_DELEGATE_MARKER)) return mod
    if (!APP_DELEGATE_WINDOW_SETUP.test(contents)) {
      // Fail the prebuild rather than ship an app with two window owners or
      // none: the template changed (an Expo upgrade?), so revisit this plugin.
      throw new Error(
        "with-scene-lifecycle: AppDelegate.swift no longer creates its window the way the " +
          "Expo SDK 55 template does. Update or remove test-app/plugins/with-scene-lifecycle.js.",
      )
    }
    mod.modResults.contents = contents.replace(
      APP_DELEGATE_WINDOW_SETUP,
      `\n    ${APP_DELEGATE_MARKER} (plugins/with-scene-lifecycle.js).\n`,
    )
    return mod
  })
}

function withSceneDelegateSource(config) {
  return withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot)
    writeFileSync(
      join(mod.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE),
      SCENE_DELEGATE,
    )
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: mod.modResults,
      })
    }
    return mod
  })
}

module.exports = function withSceneLifecycle(config) {
  return withSceneDelegateSource(withoutAppDelegateWindow(withSceneManifest(config)))
}
